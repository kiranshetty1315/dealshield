class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic 'Page X of Y' and neutral cryptographic running footer."""

    def __init__(self, *args, **kwargs):
        kwargs["pageCompression"] = 0
        kwargs["invariant"] = 1
        super().__init__(*args, **kwargs)
        self.setTitle("DealShield AI Commercial Agreement Record")
        self.setAuthor("DealShield AI")
        self.setSubject("Commercial Agreement Record")
        self._saved_page_states = []
        self.is_confirmed = False

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running bottom rule
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(36, 42, 559, 42)

        # Neutral footer text
        left_text = "DealShield AI — Plain-Language Commercial Agreement • Tamper-Evident Record"
        right_text = f"Page {self._pageNumber} of {total_pages}"

        self.drawString(36, 30, left_text)
        self.drawRightString(559, 30, right_text)

        # Honest watermark: "DRAFT RECORD" or "COMMERCIAL RECORD"
        watermark_text = "COMMERCIAL RECORD" if self.is_confirmed else "DRAFT RECORD"
        self.setFont("Helvetica-Bold", 44)
        self.setFillColor(colors.HexColor("#0F172A"), alpha=0.03)
        self.translate(297, 420)
        self.rotate(45)
        self.drawCentredString(0, 0, watermark_text)
        self.restoreState()


class StampPaperPdfService:
    """Generates neutral, transparent commercial agreement PDF documents."""

    @classmethod
    def generate_pdf(
        cls,
        agreement: Agreement,
        confirmation_status: Optional[ConfirmationStatus] = None,
    ) -> bytes:
        """Generates a downloadable commercial agreement PDF with Certificate of Assent."""
        # Auto-resolve confirmation status if omitted
        if confirmation_status is None and agreement.id:
            try:
                from app.db.repository import ConfirmationRepository
                conf_repo = ConfirmationRepository()
                confirmation_status = conf_repo.get_confirmation_status(agreement.id)
            except Exception:
                confirmation_status = None

        is_fully_confirmed = (
            confirmation_status is not None and confirmation_status.all_confirmed
        )

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=36,
            rightMargin=36,
            topMargin=36,
            bottomMargin=54,
            invariant=1,
        )

        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=15,
            leading=18,
            alignment=1,
            textColor=colors.HexColor("#0F172A"),
            spaceAfter=4,
        )

        subtitle_style = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11,
            alignment=1,
            textColor=colors.HexColor("#475569"),
            spaceAfter=10,
        )

        preamble_style = ParagraphStyle(
            "Preamble",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#1E293B"),
            spaceAfter=10,
        )

        clause_heading_style = ParagraphStyle(
            "ClauseHeading",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=10,
            leading=13,
            textColor=colors.HexColor("#0F172A"),
            spaceBefore=8,
            spaceAfter=3,
        )

        clause_body_style = ParagraphStyle(
            "ClauseBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=12,
            textColor=colors.HexColor("#334155"),
            spaceAfter=4,
        )

        statutory_style = ParagraphStyle(
            "StatutoryRef",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=7.5,
            leading=10,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=6,
        )

        cell_label_style = ParagraphStyle(
            "CellLabel",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#475569"),
        )

        cell_value_style = ParagraphStyle(
            "CellValue",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#0F172A"),
        )

        elements = []

        # ---------------------------------------------------------
        # 1. HONEST COMMERCIAL RECORD HEADER
        # ---------------------------------------------------------
        first_party = agreement.parties[0] if len(agreement.parties) > 0 else "First Party (Initiator)"
        second_party = agreement.parties[1] if len(agreement.parties) > 1 else "Second Party (Counterparty)"
        created_dt = agreement.created_at.strftime("%d-%b-%Y %I:%M %p UTC") if agreement.created_at else "Immediate"

        header_data = [
            [
                Paragraph(
                    "<font size=13><b>DEALSHIELD AI</b></font><br/>"
                    "<font size=10><b>Plain-Language Commercial Agreement (Record)</b></font><br/>"
                    "<font size=7.5 color='#475569'>Private Record of Agreed Commercial Terms Generated from Verified Negotiations</font>",
                    ParagraphStyle(
                        "TopHeader",
                        fontName="Helvetica-Bold",
                        alignment=1,
                        leading=13,
                        textColor=colors.HexColor("#0F172A"),
                    ),
                )
            ]
        ]
        header_table = Table(header_data, colWidths=[523])
        header_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("BOX", (0, 0), (-1, -1), 1.2, colors.HexColor("#334155")),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ])
        )
        elements.append(header_table)

        # Metadata Grid
        grid_data = [
            [
                Paragraph("<b>Agreement Reference</b>", cell_label_style),
                Paragraph(f"<code>{agreement.id[:18]}...</code>", cell_value_style),
                Paragraph("<b>Date Generated</b>", cell_label_style),
                Paragraph(created_dt, cell_value_style),
            ],
            [
                Paragraph("<b>Current Version</b>", cell_label_style),
                Paragraph(f"v{agreement.current_version}.0", cell_value_style),
                Paragraph("<b>Agreement Status</b>", cell_label_style),
                Paragraph(f"<b>{agreement.status.replace('_', ' ').upper()}</b>", cell_value_style),
            ],
            [
                Paragraph("<b>First Party (Initiator)</b>", cell_label_style),
                Paragraph(f"<b>{first_party}</b>", cell_value_style),
                Paragraph("<b>Second Party (Counterparty)</b>", cell_label_style),
                Paragraph(f"<b>{second_party}</b>", cell_value_style),
            ],
        ]

        grid_table = Table(grid_data, colWidths=[125, 136, 130, 132])
        grid_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F1F5F9")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ])
        )
        elements.append(grid_table)

        # Prominent Warning Notice Callout (NO fake stamp duty claims)
        warning_notice = Paragraph(
            "<font size=7 color='#92400E'><b>NOTICE:</b> "
            "This document is a private record of commercial terms agreed between the parties. "
            "It is <b>NOT</b> a government-issued stamp paper, e-Stamp certificate, or statutory non-judicial stamp paper. "
            "No stamp duty has been paid through this service. For legal proceedings requiring stamp duty under the "
            "Indian Stamp Act, 1899 or applicable State Stamp Acts, parties must independently pay stamp duty through "
            "authorised channels. Electronic assents recorded herein are based on single-use token and email-OTP "
            "verification and do not constitute an Aadhaar eSign or IT Act Section 3/3A digital signature.</font>",
            ParagraphStyle("WarningNotice", fontName="Helvetica", leading=9.5, alignment=0),
        )
        notice_table = Table([[warning_notice]], colWidths=[523])
        notice_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FFFBEB")),
                ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#F59E0B")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ])
        )
        elements.append(notice_table)
        elements.append(Spacer(1, 10))

        # ---------------------------------------------------------
        # 2. AGREEMENT TITLE & PREAMBLE
        # ---------------------------------------------------------
        elements.append(Paragraph("COMMERCIAL SERVICE AGREEMENT TERMS", title_style))
        elements.append(
            Paragraph(
                f"Agreement UUID: <code>{agreement.id}</code> &bull; Version: <b>v{agreement.current_version}.0</b>",
                subtitle_style,
            )
        )

        preamble_text = (
            f"This <b>Commercial Service Agreement</b> (&ldquo;Agreement&rdquo;) records the commercial understanding "
            f"agreed upon between the following parties: "
            f"<br/><br/>"
            f"1. <b>{first_party}</b>, hereinafter referred to as the <b>&ldquo;First Party / Initiator&rdquo;</b>, AND<br/>"
            f"2. <b>{second_party}</b>, hereinafter referred to as the <b>&ldquo;Second Party / Counterparty&rdquo;</b>.<br/><br/>"
            f"<b>RECITALS:</b> The parties conducted bilateral negotiations and have synthesized their understanding into the "
            f"terms and operational clauses documented below."
        )
        elements.append(Paragraph(preamble_text, preamble_style))
        elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceAfter=8))

        # ---------------------------------------------------------
        # 3. SYNTHESIZED CONTRACT CLAUSES
        # ---------------------------------------------------------
        latest_version = agreement.versions[-1] if agreement.versions else None
        clauses: List[Clause] = latest_version.clauses if latest_version else []

        if not clauses:
            elements.append(
                Paragraph(
                    "<i>Mutual commercial understanding as established in the communication records.</i>",
                    clause_body_style,
                )
            )
        else:
            for clause in clauses:
                clause_elements = []
                clause_elements.append(Paragraph(clause.title, clause_heading_style))
                clause_elements.append(Paragraph(clause.body.replace("\n", "<br/>"), clause_body_style))
                if clause.statutory_reference:
                    clause_elements.append(
                        Paragraph(
                            f"<b>Reference Standard:</b> {clause.statutory_reference}",
                            statutory_style,
                        )
                    )
                elements.append(KeepTogether(clause_elements))

        elements.append(Spacer(1, 10))
        elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceAfter=10))

        # ---------------------------------------------------------
        # 4. CERTIFICATE OF ASSENT SECTION
        # ---------------------------------------------------------
        elements.append(
            Paragraph(
                "<b>CERTIFICATE OF ASSENT & EXECUTION AUDIT TRAIL</b>",
                ParagraphStyle("CertTitle", fontName="Helvetica-Bold", fontSize=11, leading=14, textColor=colors.HexColor("#0F172A"), spaceAfter=4),
            )
        )
        elements.append(
            Paragraph(
                "Electronic assents recorded below reflect direct platform confirmation for the initiating party "
                "and single-use signed token with Email OTP verification for external counterparties:",
                ParagraphStyle("CertSubtitle", fontName="Helvetica", fontSize=8, leading=11, textColor=colors.HexColor("#475569"), spaceAfter=8),
            )
        )

        # Lookup confirmation statuses for both parties
        party_a_rec: Optional[PartyConfirmationRecord] = None
        party_b_rec: Optional[PartyConfirmationRecord] = None

        if confirmation_status and confirmation_status.parties:
            for p in confirmation_status.parties:
                if p.party_name.strip().lower() == first_party.strip().lower():
                    party_a_rec = p
                elif p.party_name.strip().lower() == second_party.strip().lower():
                    party_b_rec = p

        def build_assent_box(
            role_label: str,
            party_name: str,
            record: Optional[PartyConfirmationRecord],
            is_initiator: bool,
        ) -> Paragraph:
            if record and record.confirmed:
                status_label = "ASSENT RECORDED (CONFIRMED)"
                status_color = "#047857"
                confirmed_date = (
                    record.confirmed_at.strftime("%d-%b-%Y %I:%M %p UTC")
                    if record.confirmed_at
                    else "Confirmed"
                )
            elif record and record.declined:
                status_label = "DECLINED"
                status_color = "#DC2626"
                confirmed_date = (
                    record.declined_at.strftime("%d-%b-%Y %I:%M %p UTC")
                    if record.declined_at
                    else "Declined"
                )
            else:
                status_label = "PENDING CONFIRMATION"
                status_color = "#D97706"
                confirmed_date = "Awaiting confirmation"

            masked_email = record.masked_email if (record and record.masked_email) else "Not recorded"
            method_desc = (
                "Direct platform confirmation (Initiator)"
                if is_initiator
                else "Email OTP to declared counterparty address. Not an Aadhaar eSign."
            )
            ip_val = f"{record.ip_hash[:16]}..." if (record and record.ip_hash) else "Not recorded"
            ver_num = record.agreed_version_number if (record and record.agreed_version_number) else agreement.current_version
            c_hash = record.agreed_content_hash if (record and record.agreed_content_hash) else "Not recorded"

            if is_initiator:
                email_ver_text = "Not applicable (Direct Platform Assent)"
            elif record and record.email_verified_at:
                email_ver_text = record.email_verified_at.strftime("%d-%b-%Y %I:%M %p UTC")
            else:
                email_ver_text = "Not recorded"

            lines = [
                f"<font size=8 color='#64748B'><b>{role_label}</b></font><br/>",
                f"<font size=10 color='#0F172A'><b>{party_name}</b></font><br/>",
                f"<font size=8 color='{status_color}'><b>&bull; {status_label}</b></font><br/>",
                f"<font size=7 color='#334155'><b>Masked Email:</b> {masked_email}</font><br/>",
                f"<font size=7 color='#334155'><b>Email Verified:</b> {email_ver_text}</font><br/>",
                f"<font size=7 color='#334155'><b>Timestamp:</b> {confirmed_date}</font><br/>",
                f"<font size=7 color='#334155'><b>Assent Version:</b> v{ver_num}.0 &bull; <b>IP Ref:</b> <code>{ip_val}</code></font><br/>",
                f"<font size=6.5 color='#334155'><b>Agreed Hash:</b> <code>{c_hash}</code></font><br/>",
                f"<font size=6.5 color='#64748B'><b>Verification Method:</b> {method_desc}</font>",
            ]
            if record and record.declined and record.decline_reason:
                lines.append(f"<br/><font size=7 color='#DC2626'><b>Decline Reason:</b> {record.decline_reason}</font>")

            return Paragraph("".join(lines), ParagraphStyle("AssentBoxP", fontName="Helvetica", leading=10.5))

        box_a = build_assent_box("FIRST PARTY (INITIATOR)", first_party, party_a_rec, is_initiator=True)
        box_b = build_assent_box("SECOND PARTY (COUNTERPARTY)", second_party, party_b_rec, is_initiator=False)

        assent_table_data = [[box_a, box_b]]
        assent_table = Table(assent_table_data, colWidths=[256, 257])
        assent_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (0, 0), colors.HexColor("#F8FAFC")),
                ("BACKGROUND", (1, 0), (1, 0), colors.HexColor("#F8FAFC")),
                ("BOX", (0, 0), (0, 0), 0.8, colors.HexColor("#CBD5E1")),
                ("BOX", (1, 0), (1, 0), 0.8, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 9),
                ("RIGHTPADDING", (0, 0), (-1, -1), 9),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ])
        )
        elements.append(assent_table)
        elements.append(Spacer(1, 8))

        # ---------------------------------------------------------
        # 5. CRYPTOGRAPHIC INTEGRITY DIGEST
        # ---------------------------------------------------------
        content_hash = latest_version.content_hash if (latest_version and latest_version.content_hash) else (
            hashlib.sha256(agreement.id.encode()).hexdigest()
        )

        audit_text = (
            f"<b>DEALSHIELD AI CRYPTOGRAPHIC RECORD & INTEGRITY SEAL:</b><br/>"
            f"SHA-256 Agreement Fingerprint: <code>{content_hash}</code><br/>"
            f"Generated: {created_dt} &bull; Private Commercial Record &bull; Notary/Statutory Stamp Duty Not Included."
        )
        audit_paragraph = Paragraph(
            audit_text,
            ParagraphStyle("AuditSealP", fontName="Helvetica", fontSize=7, leading=9.5, textColor=colors.HexColor("#1E293B")),
        )
        audit_table = Table([[audit_paragraph]], colWidths=[523])
        audit_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F1F5F9")),
                ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#94A3B8")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ])
        )
        elements.append(audit_table)

        # Build document with custom two-pass canvas
        def make_canvas(*args, **kwargs):
            canv = NumberedCanvas(*args, **kwargs)
            canv.is_confirmed = is_fully_confirmed
            return canv

        doc.build(elements, canvasmaker=make_canvas)
        buffer.seek(0)
        return buffer.getvalue()
